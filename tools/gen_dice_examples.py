"""Generate example dice-set packs that can be uploaded in Settings → Dice → Dice sets.

Usage: python3 tools/gen_dice_examples.py [out_dir]     (default: docs/dice-examples)
Requires Pillow (pip install pillow).

Writes two ZIPs:
- wood.zip: a full pack whose manifest.json lists everything: colours, a 2D image for every
  die, 3D face textures for d4-d100 and pips on the d6.
- neon.zip: a short manifest with colours only; the images and the font are matched by
  file name (2d/d6.png, 2d/d20.png, 3d/d20_face.png, dN.png, fonts/segments.ttf). The font
  is an original seven-segment face generated by tools/segment_font.py.

Shapes come from tools/gen_dice_templates.py, so the images match the app's silhouettes and
face outlines. Randomness is seeded and ZIP timestamps are fixed, so reruns give identical files.
"""
import io
import json
import math
import os
import random
import sys
import zipfile

from PIL import Image, ImageChops, ImageDraw, ImageFilter

sys.path.insert(0, os.path.dirname(__file__))
import segment_font  # noqa: E402
from gen_dice_templates import D100_KITE_OFFSETS, D100_KITE_SCALE, D100_KITE_TOP, FACES_3D, SHAPES_2D  # noqa: E402

SIZE = 512
SS = 4  # supersampling factor for smooth edges
BIG = SIZE * SS
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "docs", "dice-examples")
ZIP_DATE = (2026, 1, 1, 0, 0, 0)


def rgb(hex_color):
    hex_color = hex_color.lstrip("#")
    return tuple(int(hex_color[i:i + 2], 16) for i in (0, 2, 4))


# ---------- shapes ----------

def shape_mask(key, inset=0.0):
    """L-mode mask (BIG×BIG) of a 2D silhouette, shrunk by [inset] (fraction of the canvas)."""
    mask = Image.new("L", (BIG, BIG), 0)
    draw = ImageDraw.Draw(mask)
    shape, _ = SHAPES_2D[key]
    lo, hi = inset * BIG, (1 - inset) * BIG
    if shape is None:
        draw.rounded_rectangle([lo, lo, hi, hi], radius=0.14 * BIG * (1 - 2 * inset), fill=255)
    elif shape == "circle":
        draw.ellipse([lo + 2 * SS, lo + 2 * SS, hi - 2 * SS, hi - 2 * SS], fill=255)
    else:
        cx = sum(x for x, _ in shape) / len(shape)
        cy = sum(y for _, y in shape) / len(shape)
        k = 1 - 2 * inset
        draw.polygon([((cx + (x - cx) * k) * BIG, (cy + (y - cy) * k) * BIG) for x, y in shape], fill=255)
    return mask


def d100_mask(inset=0.0):
    """Two d10 kites side by side, as the app draws a d100 (caption area below stays empty)."""
    mask = Image.new("L", (BIG, BIG), 0)
    kite = shape_mask("d10", inset)
    small = kite.resize((round(BIG * D100_KITE_SCALE),) * 2, Image.LANCZOS)
    for ox in D100_KITE_OFFSETS:
        layer = Image.new("L", (BIG, BIG), 0)
        layer.paste(small, (round(ox * BIG), round(D100_KITE_TOP * BIG)))
        mask = ImageChops.lighter(mask, layer)
    return mask


def die_mask(key, inset=0.0):
    return d100_mask(inset) if key == "d100" else shape_mask(key, inset)


def label_centre(key):
    return (0.5, 0.78) if key == "d100" else SHAPES_2D[key][1]


def face_points(key):
    """3D face outline in BIG pixels, scaled like the templates (circumradius = half the canvas)."""
    pts = FACES_3D["d10" if key == "d100" else key]
    r = max(math.hypot(x, y) for x, y in pts)
    scale = (BIG / 2) / r
    return [(BIG / 2 + x * scale, BIG / 2 + y * scale) for x, y in pts]


def inset_points(points, k):
    cx = sum(x for x, _ in points) / len(points)
    cy = sum(y for _, y in points) / len(points)
    return [(cx + (x - cx) * k, cy + (y - cy) * k) for x, y in points]


# ---------- textures ----------

def wood_grain(seed, base, dark, light):
    """Seeded wood grain: wavy horizontal strokes over a base colour, softly blurred."""
    rnd = random.Random(seed)
    img = Image.new("RGB", (BIG, BIG), rgb(base))
    draw = ImageDraw.Draw(img)
    y = -40.0
    while y < BIG + 40:
        amp = rnd.uniform(6, 22) * SS
        freq = rnd.uniform(0.6, 1.6) * 2 * math.pi / BIG
        phase = rnd.uniform(0, 2 * math.pi)
        colour = rgb(dark) if rnd.random() < 0.65 else rgb(light)
        width = rnd.randint(1, 4) * SS
        pts = [(x, y + amp * math.sin(freq * x + phase)) for x in range(0, BIG + 16, 16)]
        draw.line(pts, fill=colour, width=width, joint="curve")
        y += rnd.uniform(5, 16) * SS
    # a couple of knots
    for _ in range(2):
        kx, ky = rnd.uniform(0.15, 0.85) * BIG, rnd.uniform(0.15, 0.85) * BIG
        for ring in range(5, 0, -1):
            rr = ring * 9 * SS
            draw.ellipse([kx - rr * 1.6, ky - rr, kx + rr * 1.6, ky + rr], outline=rgb(dark), width=2 * SS)
    return img.filter(ImageFilter.GaussianBlur(1.2 * SS))


def calm_spot(img, centre, radius, colour, strength):
    """Fades busy detail towards [colour] around [centre] so labels and numbers stay readable."""
    spot = Image.new("L", img.size, 0)
    cx, cy = centre[0] * img.width, centre[1] * img.height
    ImageDraw.Draw(spot).ellipse([cx - radius, cy - radius * 0.75, cx + radius, cy + radius * 0.75], fill=round(255 * strength))
    spot = spot.filter(ImageFilter.GaussianBlur(radius * 0.35))
    return Image.composite(Image.new("RGB", img.size, rgb(colour)), img, spot)


def finish(img):
    return img.resize((SIZE, SIZE), Image.LANCZOS)


# ---------- wood set ----------

WOOD = dict(base="#8D6E63", dark="#5D4037", light="#A1887F", edge="#3E2723", calm="#8D6E63")
WOOD_DARK = dict(base="#5D4037", dark="#3E2723", light="#795548", edge="#21130F", calm="#5D4037")


def wood_2d(key, seed, palette):
    body = wood_grain(seed, palette["base"], palette["dark"], palette["light"])
    body = calm_spot(body, label_centre(key), 0.2 * BIG, palette["calm"], 0.8)
    outer = die_mask(key)
    inner = die_mask(key, inset=0.035 if key != "d100" else 0.06)
    out = Image.new("RGBA", (BIG, BIG), (0, 0, 0, 0))
    out.paste(Image.new("RGB", (BIG, BIG), rgb(palette["edge"])), (0, 0), outer)
    out.paste(body, (0, 0), inner)
    return finish(out)


def wood_face(key, seed, palette):
    # Grain only: the renderer strokes the face edges itself, so a drawn border would show twice.
    img = wood_grain(seed, palette["base"], palette["dark"], palette["light"])
    img = calm_spot(img, (0.5, 0.5), 0.22 * BIG, palette["calm"], 0.75)
    return finish(img.convert("RGBA"))


def wood_pack():
    files = {}
    dice = {}
    keys = ["d4", "d6", "d8", "d10", "d12", "d20", "d100", "dN"]
    for i, key in enumerate(keys):
        palette = WOOD_DARK if key == "d20" else WOOD
        files[f"2d/{key}.png"] = wood_2d(key, 100 + i, palette)
        spec = {"image2d": f"2d/{key}.png"}
        if key != "dN":
            files[f"3d/{key}_face.png"] = wood_face(key, 200 + i, palette)
            spec["faceTexture3d"] = f"3d/{key}_face.png"
        dice[key] = spec
    dice["d6"]["pips"] = True
    dice["d20"]["fill"] = WOOD_DARK["base"]
    dice["d20"]["edge"] = WOOD_DARK["edge"]
    manifest = {
        "formatVersion": 1,
        "id": "wood",
        "name": "Wood",
        "style": {"fill": WOOD["base"], "edge": WOOD["edge"], "text": "#FFF8E1", "edgeWidth": 2},
        "dice": dice,
    }
    return manifest, files


# ---------- neon set (colours in the manifest, files found by name) ----------

NEON_BODY = "#1A1033"
NEON_CYAN, NEON_PINK, NEON_GREEN = "#00E5FF", "#FF4081", "#B2FF59"


def neon_glow(mask_outer, mask_inner, colour):
    """A glowing rim between two masks, kept inside the silhouette."""
    rim = ImageChops.subtract(mask_outer, mask_inner)
    glow = rim.filter(ImageFilter.GaussianBlur(10 * SS))
    glow = ImageChops.multiply(ImageChops.add(glow, glow), mask_outer)
    layer = Image.new("RGBA", (BIG, BIG), rgb(colour) + (0,))
    layer.putalpha(ImageChops.lighter(glow, rim))
    return layer


def neon_2d(key, colour):
    outer = die_mask(key)
    out = Image.new("RGBA", (BIG, BIG), (0, 0, 0, 0))
    out.paste(Image.new("RGB", (BIG, BIG), rgb(NEON_BODY)), (0, 0), outer)
    out.alpha_composite(neon_glow(outer, die_mask(key, inset=0.03), colour))
    return finish(out)


def neon_face(key, colour):
    """Dark face with a soft inner glow; the renderer draws the neon edge line on top."""
    img = Image.new("RGBA", (BIG, BIG), rgb(NEON_BODY) + (255,))
    pts = face_points(key)
    outer = Image.new("L", (BIG, BIG), 0)
    ImageDraw.Draw(outer).polygon(pts, fill=255)
    inner = Image.new("L", (BIG, BIG), 0)
    ImageDraw.Draw(inner).polygon(inset_points(pts, 0.7), fill=255)
    glow = ImageChops.subtract(outer, inner).filter(ImageFilter.GaussianBlur(24 * SS))
    layer = Image.new("RGBA", (BIG, BIG), rgb(colour) + (0,))
    layer.putalpha(glow.point(lambda v: v * 3 // 5))
    img.alpha_composite(layer)
    return finish(img)


def neon_pack():
    # The manifest only sets colours; the images and the font are matched by file name.
    manifest = {
        "formatVersion": 1,
        "id": "neon",
        "name": "Neon",
        "style": {"fill": NEON_BODY, "edge": NEON_CYAN, "text": NEON_CYAN, "edgeWidth": 2.5},
        "dice": {
            "d20": {"edge": NEON_PINK, "text": NEON_PINK},
            "dN": {"edge": NEON_GREEN, "text": NEON_GREEN},
        },
    }
    return manifest, {
        "2d/d6.png": neon_2d("d6", NEON_CYAN),
        "2d/d20.png": neon_2d("d20", NEON_PINK),
        "3d/d20_face.png": neon_face("d20", NEON_PINK),
        "dN.png": neon_2d("dN", NEON_GREEN),
        "fonts/segments.ttf": segment_font.build(),
    }


# ---------- output ----------

def write_zip(path, manifest, files):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        def add(name, data):
            info = zipfile.ZipInfo(name, date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, data)

        if manifest is not None:
            add("manifest.json", json.dumps(manifest, indent=2) + "\n")
        for name in sorted(files):
            data = files[name]
            if isinstance(data, Image.Image):
                buf = io.BytesIO()
                data.save(buf, "PNG", optimize=True)
                data = buf.getvalue()
            add(name, data)
    print(f"{path}: {', '.join(sorted(files))}{'' if manifest is None else ' + manifest.json'}")


def main():
    os.makedirs(OUT, exist_ok=True)
    write_zip(os.path.join(OUT, "wood.zip"), *wood_pack())
    write_zip(os.path.join(OUT, "neon.zip"), *neon_pack())


if __name__ == "__main__":
    main()
